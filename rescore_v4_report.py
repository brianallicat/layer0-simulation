"""Writes RESCORE_V4.md from results_rescore_v4.json (+ cross-checks against results_eval_v2.json and
evolve_results.json, both read-only). Also regrows the 26 base bodies (deterministic) to read their
pre-cut organizer positions for the wedge explanation."""
from __future__ import annotations

import json
import os

import numpy as np

from experiments import GROW_STEPS, _orgs
from sim import Config, World
import rescore_v4 as R4

HERE = os.path.dirname(os.path.abspath(__file__))
J = lambda f: json.load(open(os.path.join(HERE, f)))
res = J("results_rescore_v4.json")
v2 = J("results_eval_v2.json")
evo = J("evolve_results.json")
rows = res["rows"]
WEDGE, CORE = R4.STRUCT[3], R4.STRUCT[2]


def ci(w):
    return f"{w[0]*100:.0f}–{w[1]*100:.0f}%"


def cell(t):
    return f"{t['k']}/{t['n']} ({t['rate']*100:.0f}%; Wilson 95% {ci(t['wilson95'])})"


L = ["# Layer 0 — rescore v4: one held-out seed set, all cuts, both honest references", "",
     "Generated by `python3 rescore_v4.py` (runs) and `python3 rescore_v4_report.py` (this file) from "
     "`results_rescore_v4.json` (per-step curves and final patterns in `results_rescore_v4_curves.npz`). "
     "Addition only: no existing module or results file was edited.", "",
     "## Protocol", "",
     f"- Bodies: hand-written genome, default simulator (Config defaults: positional memory, organizer re-derivation, "
     f"proofreading, redundancy all ON), λ={res['protocol']['lam']}, grown {res['protocol']['grow_steps']} steps, then "
     f"{res['protocol']['regen_steps']} steps after the cut with rng {res['protocol']['twin_rng']} (same as eval_v2 and the evolve track).",
     f"- Held-out seeds (union of eval_v2 and evolve-track sets, n={len(R4.HELDOUT)}): {', '.join(map(str, R4.HELDOUT))}. "
     "Tuned seed 0 is run separately; it is also the seed-0 reference body, so it is never scored against it.",
     "- Cuts: the eval_v2 damage catalog, 16 per body: the 4 structured cuts + 5 angled/depth amputations + "
     "3 two-organizer losses + 4 random discs.",
     "- Every step is scored against two references, both free of self-reference:",
     "  - **own** — the body's own pre-cut pattern; floor = its undamaged twin vs that pattern (eval_v2 convention).",
     "  - **ref0** — the seed-0 hand-written body at step 200; floor = the undamaged twin vs ref0 (evolve-track convention).",
     f"- Verdict: {res['protocol']['rule']}. Rates carry Wilson 95% intervals.", ""]

# ---------------- cross-checks ----------------
v2rows = {(r["seed"], r["name"]): r for r in v2["catalog_rows"] if r["cond"] == "ON"}
same = diff = 0
for r in rows:
    k = (r["seed"], r["name"])
    if k in v2rows:
        if v2rows[k]["recovered_sustained"] == r["own"]["recovered_sustained"] and \
                abs(v2rows[k]["last50_mean"] - r["own"]["last50_mean"]) < 1e-9:
            same += 1
        else:
            diff += 1
ev = {p["seed"]: p for p in evo["held_out"]["hand-written (wild type)"]["per_seed"]}
es = ed = 0
for r in rows:
    if r["seed"] in ev and r["name"] in ev[r["seed"]]["cuts"]:
        e = ev[r["seed"]]["cuts"][r["name"]]
        if e["sustained"] == r["ref0"]["recovered_sustained"] and abs(e["last50_mean"] - r["ref0"]["last50_mean"]) < 1e-9:
            es += 1
        else:
            ed += 1
L += ["## 0. Reproduction check", "",
      f"- vs `results_eval_v2.json` (own reference, overlapping seed×cut cases): {same} identical (verdict and last-50 mean to 1e-9), {diff} different.",
      f"- vs `evolve_results.json` (ref0, hand-written, overlapping seed×cut cases): {es} identical, {ed} different.",
      "- So the two earlier results are reproduced exactly; the disagreement is the reference, not the runs.", ""]

# ---------------- unified table ----------------
P = res["passes"]
L += ["## 1. Unified results (held-out, ON)", "",
      "| cut | own reference (twin floor) | seed-0 reference | own, eval_v2 21 seeds | ref0, evolve 10 seeds |",
      "|---|---|---|---|---|"]
for g in R4.STRUCT + ["angled/depth amputation", "two organizers lost", "random disc (NCA-style)", "ALL 16 cuts"]:
    L.append(f"| {g} | {cell(P['union_25']['own'][g])} | {cell(P['union_25']['ref0'][g])} | "
             f"{cell(P['eval_v2_21']['own'][g])} | {cell(P['evolve_10']['ref0'][g])} |")
L += ["", "Failing seeds (union set):", ""]
for g in R4.STRUCT:
    L.append(f"- {g}: own → {P['union_25']['own'][g]['failing'] or 'none'}; ref0 → {P['union_25']['ref0'][g]['failing'] or 'none'}")
# agreement matrix for wedge and core
L += [""]
for g in (WEDGE, CORE):
    rr = [r for r in rows if r["name"] == g and r["seed"] in R4.HELDOUT]
    m = {(a, b): sum(1 for r in rr if r["own"]["recovered_sustained"] == a and r["ref0"]["recovered_sustained"] == b)
         for a in (True, False) for b in (True, False)}
    L.append(f"- {g}, agreement (own/ref0): pass/pass {m[(True, True)]}, pass/fail {m[(True, False)]}, "
             f"fail/pass {m[(False, True)]}, fail/fail {m[(False, False)]} (n={len(rr)})")
s0 = res["tuned_seed0_own"]
L += ["", "Tuned seed 0 (own reference only): " + "; ".join(
    f"{n.split(' (')[0]} {'YES' if s0[n]['recovered_sustained'] else 'no'} (last-50 {s0[n]['last50_mean']:.4f} vs floor {s0[n]['floor']:.4f})"
    for n in R4.STRUCT), ""]
fs = res["floor_stats"]
L += [f"Floors over the 25 held-out bodies: own {fs['own']['mean']:.4f} ± {fs['own']['sd']:.4f} SD "
      f"(range {fs['own']['min']:.4f}–{fs['own']['max']:.4f}); ref0 {fs['ref0']['mean']:.4f} ± {fs['ref0']['sd']:.4f} SD "
      f"(range {fs['ref0']['min']:.4f}–{fs['ref0']['max']:.4f}).", ""]

# ---------------- wedge explanation ----------------
bases = {s: World(Config(seed=s, lam=R4.LAM)).run(GROW_STEPS) for s in [0] + R4.HELDOUT}
orgs0 = {s: _orgs(b) for s, b in bases.items()}
g = res["growth"]["vs_seed0_by_seed"]
L += ["## 2. Why the wedge verdict depends on the reference", "",
      "Per held-out body, posterior wedge. `growth` = pre-cut body vs ref0. Gap = floor − last-50 mean "
      "(positive = below floor; fails if > 0.03 or < 40/50 steps within). P before/after = posterior organizer "
      "position (row, col) in the pre-cut body / at the end of the run; seed-0 P = " + str(orgs0[0]["P"]) + ".", "",
      "| seed | growth vs ref0 | own floor | own last-50 | own gap | own | ref0 floor | ref0 last-50 | ref0 gap | ref0 | P before | P after | changed cells | of which pre-cut already ≠ ref0 | changed cells now = ref0 |",
      "|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|"]
wr = sorted([r for r in rows if r["name"] == WEDGE and r["seed"] in R4.HELDOUT], key=lambda r: r["seed"])
for r in wr:
    o, f, d = r["own"], r["ref0"], r["decomposition_final"]
    L.append(f"| {r['seed']} | {g[str(r['seed'])]:.4f} | {o['floor']:.4f} | {o['last50_mean']:.4f} | {o['floor']-o['last50_mean']:+.4f} | "
             f"{'YES' if o['recovered_sustained'] else 'no'} | {f['floor']:.4f} | {f['last50_mean']:.4f} | {f['floor']-f['last50_mean']:+.4f} | "
             f"{'YES' if f['recovered_sustained'] else 'no'} | {orgs0[r['seed']].get('P')} | {r['orgs_after'].get('P')} | "
             f"{d['cells_changed_vs_own']} | {d['changed_where_precut_already_differed_from_ref0']} | {d['changed_cells_now_matching_ref0']} |")
go = np.array([r["own"]["floor"] - r["own"]["last50_mean"] for r in wr])
gr = np.array([r["ref0"]["floor"] - r["ref0"]["last50_mean"] for r in wr])
gs = np.array([g[str(r["seed"])] for r in wr])
fr = np.array([r["ref0"]["floor"] for r in wr])
lr = np.array([r["ref0"]["last50_mean"] for r in wr])
ch = np.array([r["decomposition_final"]["cells_changed_vs_own"] for r in wr])
pre = np.array([r["decomposition_final"]["changed_where_precut_already_differed_from_ref0"] for r in wr])
lands = np.array([r["decomposition_final"]["changed_cells_now_matching_ref0"] for r in wr])
def _p(o):
    return [list(map(int, x)) for x in (o.get("P") or [])]
p0row = _p(orgs0[0])[0][0]
same_after = sum(1 for r in wr if _p(r["orgs_after"]) and _p(r["orgs_after"])[0][0] == p0row)
same_before = sum(1 for r in wr if _p(orgs0[r["seed"]]) and _p(orgs0[r["seed"]])[0][0] == p0row)
L += ["", "Summary (25 held-out wedge cases):", "",
      f"- Mean gap to floor: own {go.mean():+.4f} ± {go.std(ddof=1):.4f} SD; ref0 {gr.mean():+.4f} ± {gr.std(ddof=1):.4f} SD.",
      f"- Cases where the cut body is CLOSER to ref0 than its own undamaged twin is (ref0 gap < 0): {int((gr < 0).sum())} of {len(gr)}.",
      f"- Correlation across seeds of the ref0 gap with the body's growth similarity to ref0: r = {np.corrcoef(gs, gr)[0,1]:+.3f}; "
      f"of the own gap with it: r = {np.corrcoef(gs, go)[0,1]:+.3f}.",
      f"- Correlation of the ref0 last-50 mean with the ref0 floor: r = {np.corrcoef(fr, lr)[0,1]:+.3f} "
      f"(ref0 floor range {fr.min():.4f}–{fr.max():.4f}; ref0 last-50 range {lr.min():.4f}–{lr.max():.4f}).",
      f"- Cells changed by the wedge (final vs own pre-cut body): {ch.mean():.1f} per body on average; "
      f"{pre.sum()/ch.sum()*100:.1f}% of them sit where the pre-cut body already differed from ref0, and "
      f"{lands.sum()/ch.sum()*100:.1f}% now agree with ref0.",
      f"- Bodies whose P sits in seed-0's P row ({p0row}): before the cut {same_before} of {len(wr)}; after regrowth {same_after} of {len(wr)}.", ""]

prow_b = np.array([_p(orgs0[r["seed"]])[0][0] for r in wr], float)
prow_a = np.array([_p(r["orgs_after"])[0][0] for r in wr], float)
disc = [i for i, r in enumerate(wr) if not r["own"]["recovered_sustained"] and r["ref0"]["recovered_sustained"]]
ff = [i for i, r in enumerate(wr) if not r["own"]["recovered_sustained"] and not r["ref0"]["recovered_sustained"]]
def grp(ix, name):
    ix = np.array(ix)
    return (f"- {name} (n={len(ix)}): growth vs ref0 {gs[ix].mean():.4f} (range {gs[ix].min():.4f}–{gs[ix].max():.4f}); "
            f"own gap {go[ix].mean():+.4f}; ref0 gap {gr[ix].mean():+.4f}; share of changed cells that now agree with ref0 "
            f"{lands[ix].sum()/ch[ix].sum()*100:.1f}%")
L += [f"- P organizer row across the 25 bodies (seed 0: row {p0row}): before the cut mean {prow_b.mean():.2f}, SD {prow_b.std(ddof=1):.2f}, "
      f"range {prow_b.min():.0f}–{prow_b.max():.0f}, mean |row − {p0row}| {np.abs(prow_b-p0row).mean():.2f}; after regrowth mean {prow_a.mean():.2f}, "
      f"SD {prow_a.std(ddof=1):.2f}, range {prow_a.min():.0f}–{prow_a.max():.0f}, mean |row − {p0row}| {np.abs(prow_a-p0row).mean():.2f}.",
      grp(disc, "fail under own, pass under ref0"), grp(ff, "fail under both"),
      grp([i for i, r in enumerate(wr) if r["own"]["recovered_sustained"]], "pass under both"), ""]

from collections import Counter
cb = Counter(_p(orgs0[r["seed"]])[0][1] for r in wr); ca = Counter(_p(r["orgs_after"])[0][1] for r in wr)
L += [f"- P organizer column (radial position along the A–core axis; seed 0: column {_p(orgs0[0])[0][1]}): before the cut "
      + ", ".join(f"col {k}: {v}" for k, v in sorted(cb.items())) + "; after regrowth "
      + ", ".join(f"col {k}: {v}" for k, v in sorted(ca.items())) + f" (n={len(wr)}).", ""]
json.dump(dict(wedge_gap_own=go.tolist(), wedge_gap_ref0=gr.tolist(), growth=gs.tolist(),
               orgs_before={str(k): v for k, v in orgs0.items()}),
          open(os.path.join(HERE, "rescore_v4_wedge_diag.json"), "w"), indent=1, default=str)

# ---------------- core failure modes ----------------
cr = sorted([r for r in rows if r["name"] == CORE and r["seed"] in R4.HELDOUT], key=lambda r: r["seed"])
dis = [r["seed"] for r in cr if r["cells_final"] == 0]
plat = [r for r in cr if r["cells_final"] > 0 and not r["own"]["recovered_sustained"]]
ok = [r["seed"] for r in cr if r["own"]["recovered_sustained"]]
L += ["## 3. Core excision failure modes (own reference, held-out union)", "",
      f"- Recovered (sustained): {len(ok)} — seeds {ok}.",
      f"- Body dissolved completely (0 cells at step 400): {len(dis)} — seeds {dis}.",
      f"- Survived but plateaued below threshold: {len(plat)} — " + ", ".join(
          f"s{r['seed']} {r['own']['last50_mean']:.4f} (C after {r['orgs_after'].get('C')}, before {orgs0[r['seed']].get('C')})" for r in plat) + ".",
      ""]

# ---------------- growth reconciliation ----------------
G = res["growth"]
def gst(s):
    return f"{s['mean']:.4f} ± {s['sd']:.4f} SD [boot 95% CI {s['ci95'][0]:.4f}–{s['ci95'][1]:.4f}] (n={s['n']})"
L += ["## 4. Growth similarity reconciled", "",
      f"All values: plain (unaligned) similarity, {G['label']}. The metric and the body growth are identical; only the "
      "seed set (and, for the pairwise number, the reference) differ.", "",
      "| number | reference | seeds | value |", "|---|---|---|---|",
      f"| paper 0.946 (results.json) | seed-0 body | 1–10 | {gst(G['paper_seeds_1_10_vs_seed0'])} |",
      f"| eval_v2 0.938 | seed-0 body | 1–19, 42, 10000 | {gst(G['eval_v2_heldout_vs_seed0'])} |",
      f"| evolve 0.928 | seed-0 body | 4, 6, 7, 42, 10000, 13, 21, 77, 314, 2026 | {gst(G['evolve_heldout_vs_seed0'])} |",
      f"| union (this run) | seed-0 body | 25 held-out | {gst(G['union_heldout_vs_seed0'])} |",
      f"| eval_v2 0.934 | every other body (per-body mean) | 0–19, 42, 10000 | {gst(G['eval_v2_all_pairs_excl_self_22_bodies'])} |",
      f"| union pairwise (this run) | every other body | 0 + 25 held-out | {gst(G['union_all_pairs_excl_self_26_bodies'])} |",
      "", "Per-seed similarity to the seed-0 body: " + ", ".join(f"s{k}={v:.4f}" for k, v in G["vs_seed0_by_seed"].items()), ""]
interp = os.path.join(HERE, "RESCORE_V4_interpretation.md")
extra = ("\n" + open(interp).read()) if os.path.exists(interp) else ""
open(os.path.join(HERE, "RESCORE_V4.md"), "w").write("\n".join(L) + "\n" + extra)
print("\n".join(L))
